package stockutil

// ============================================================
// stockutil/board.go - 板块判断工具
// ============================================================
// 这个文件提供股票板块判断功能。
//
// 【A 股板块分类】
// - 沪市主板: 600/601/603/605 开头
// - 深市主板: 000/001/002/003 开头
// - 创业板: 300 开头（风险较高，涨跌幅限制 20%）
// - 科创板: 688 开头（风险较高，涨跌幅限制 20%）
// - 北交所: 4/8/9 开头
//
// 【为什么需要过滤板块？】
// 不同板块的交易规则不同：
// - 主板涨跌幅限制 10%，创业板/科创板 20%
// - 主板流动性更好，策略更容易执行
// - 回测时只选择主板股票，结果更有代表性
// ============================================================

import "strings" // 字符串处理

// IsValidMainBoardCode 判断股票代码是否属于主板（沪深主板）。
// 【允许的前缀】
// - 000/001/002/003: 深市主板
// - 600/601/603/605: 沪市主板
//
// 【排除的板块】
// - 300: 创业板
// - 688: 科创板
// - 4/8/9 开头: 北交所
//
// 【参数】
// tsCode: 股票代码，如 "000001.SZ" 或 "600519.SH"
//
// 【返回值】
// true: 是主板股票
// false: 不是主板股票
func IsValidMainBoardCode(tsCode string) bool {
	// 取 "." 之前的部分作为纯数字代码
	// 例如: "000001.SZ" → "000001"
	code := tsCode
	if idx := strings.IndexByte(tsCode, '.'); idx >= 0 {
		code = tsCode[:idx]
	}

	// 代码长度至少 3 位
	if len(code) < 3 {
		return false
	}

	// 取前 3 位作为前缀
	prefix3 := code[:3]

	// 判断是否属于主板
	switch prefix3 {
	case "000", "001", "002", "003", // 深市主板
		"600", "601", "603", "605": // 沪市主板
		return true
	}
	return false
}
